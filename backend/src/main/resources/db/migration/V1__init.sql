create table imagen (
    id           bigint generated by default as identity primary key,
    content_type varchar(100) not null,
    datos        bytea        not null
);

create table cuerda_set (
    id           bigint generated by default as identity primary key,
    tipo         varchar(20)  not null,
    descripcion  varchar(500) not null,
    cantidad     integer      not null default 1,
    fecha_compra date,
    fecha_cambio date,
    notas        varchar(2000),
    imagen_id    bigint references imagen (id) on delete set null
);

create index idx_cuerda_set_tipo on cuerda_set (tipo);
